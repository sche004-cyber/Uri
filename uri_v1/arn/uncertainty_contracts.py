"""ARN Foundation: Uncertainty Discovery & Question Framing Contracts (Batch A2.8A).

Governing Principles:
1. "URI defines URI. Models provide replaceable cognitive capacity."
2. "StructuralSignal != SemanticConclusion": Detecting or preserving a marker (e.g. 'don't')
   does NOT authorize URI to hard-code a semantic outcome (e.g. 'SEND = PROHIBITED').
   The harness preserves markers, spans, candidate relationships, and provenance;
   semantic interpretation remains cognitive.
3. Permanent Harness Principle: URI hard-codes control semantics, authority, and
   deterministic system invariants — not human-language replies or brittle natural-language
   interpretation heuristics.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional, Sequence, Tuple


class StructuralSignalType(str, Enum):
    """Categories of syntactic, lexical, and structural cues detected in the turn."""

    NEGATION_MARKER = "NEGATION_MARKER"          # "don't", "do not", "not", "never", "without", "avoid", "stop"
    CONTRAST_MARKER = "CONTRAST_MARKER"          # "but", "instead", "rather than", "however", "except"
    CONDITIONAL_MARKER = "CONDITIONAL_MARKER"    # "if", "unless", "only if", "provided that", "in case"
    TEMPORAL_MARKER = "TEMPORAL_MARKER"          # "until", "after", "before", "once", "tomorrow", "next Monday"
    ACTION_VERB = "ACTION_VERB"                  # detected action candidate (e.g. "send", "draft", "shred")
    TARGET_MENTION = "TARGET_MENTION"            # detected target/object entity
    UNRESOLVED_REFERENCE = "UNRESOLVED_REFERENCE"# reference unanchored by RAR
    AMBIGUOUS_REFERENCE = "AMBIGUOUS_REFERENCE"  # reference tied to multiple candidates in RAR
    COORDINATION_MARKER = "COORDINATION_MARKER"  # "and", "or", "as well as"
    MODIFIER_MARKER = "MODIFIER_MARKER"          # "appropriately", "urgently", "as needed"


@dataclass(frozen=True)
class StructuralSignal:
    """A preserved structural marker or cue with explicit text span and provenance.

    INVARIANT:
        StructuralSignal != SemanticConclusion.
        Preserves evidence without deciding the semantic outcome.
    """

    signal_type: StructuralSignalType
    span_text: str
    start_char: int
    end_char: int
    associated_verb: Optional[str] = None
    associated_target: Optional[str] = None
    clause_index: int = 0
    provenance: str = "TurnFrame"


class UncertaintyType(str, Enum):
    """Taxonomy of semantic uncertainties requiring cognitive resolution."""

    UNRESOLVED_REFERENCE = "UNRESOLVED_REFERENCE"    # What known entity does this pronoun/phrase bind to?
    NEGATION_SCOPE = "NEGATION_SCOPE"                # Which operation(s) does the negative marker govern?
    CONDITIONAL_DEPENDENCY = "CONDITIONAL_DEPENDENCY"# Under what explicit condition is the action contingent?
    TEMPORAL_DEPENDENCY = "TEMPORAL_DEPENDENCY"      # What is the temporal constraint / gating trigger?
    OPERATION_TARGET = "OPERATION_TARGET"            # Which specific object is the target of which verb?
    OPERATION_POLARITY = "OPERATION_POLARITY"        # Is the operation requested, prohibited, or deferred?
    CONTRAST_RELATIONSHIP = "CONTRAST_RELATIONSHIP"  # How do the contrasting clauses relate?
    AMBIGUOUS_COORDINATION = "AMBIGUOUS_COORDINATION"# Does the modifier/action distribute over both targets?
    MODIFIER_SCOPE = "MODIFIER_SCOPE"                # What does the qualifier modify?


@dataclass(frozen=True)
class SemanticUncertainty:
    """An explicit, unresolved semantic question identified after TurnFrame + RAR.

    Represents: 'What still needs to be understood?' without pre-determining the answer.
    """

    uncertainty_id: str
    uncertainty_type: UncertaintyType
    description: str
    relevance_justification: str
    anchored_signals: Tuple[StructuralSignal, ...] = ()
    is_critical: bool = True  # If true, omitting or misinterpreting this alters execution/safety
    provenance: str = "UncertaintyDiscovery"


class QuestionFramingMethod(str, Enum):
    """Method utilized to formulate narrow questions."""

    METHOD_A_DETERMINISTIC = "METHOD_A_DETERMINISTIC"  # Pure structural rule-based question synthesis
    METHOD_B_MODEL_ASSISTED = "METHOD_B_MODEL_ASSISTED"# Generated by prompt to local cognitive model
    METHOD_C_HYBRID = "METHOD_C_HYBRID"                # Deterministic evidence + model framing + validator


@dataclass(frozen=True)
class FramedQuestion:
    """A focused, neutral semantic question posed to resolve an uncertainty.

    Must be atomic, neutral, grounded, and non-leading.
    """

    question_id: str
    uncertainty_id: str
    question_text: str
    framing_method: QuestionFramingMethod
    grounded_spans: Tuple[str, ...] = ()
    expected_answer_type: str = "clarification"  # "boolean", "candidate_selection", "clarification"
    is_neutral: bool = True
    is_atomic: bool = True
    presupposes_answer: bool = False
    provenance: str = ""


class QuestionValidationFlag(str, Enum):
    """Flags raised when a framed question violates neutrality or grounding."""

    VALID = "VALID"
    PRESUPPOSES_ANSWER = "PRESUPPOSES_ANSWER"          # Leading question (e.g. "Why is sending forbidden?")
    UNGROUNDED_REFERENT = "UNGROUNDED_REFERENT"        # Invented entity not in text or working memory
    LOST_CRITICAL_SIGNAL = "LOST_CRITICAL_SIGNAL"      # Failed to include the preserved structural signal
    COMBINED_UNCERTAINTIES = "COMBINED_UNCERTAINTIES"  # Bundled multiple distinct questions (non-atomic)
    DUPLICATE_QUESTION = "DUPLICATE_QUESTION"          # Redundant with an already framed question
    NOT_ADDRESSING_UNCERTAINTY = "NOT_ADDRESSING_UNCERTAINTY"  # Irrelevant to the declared uncertainty


@dataclass(frozen=True)
class QuestionValidationResult:
    """Result of validating a framed question against neutrality and grounding gates."""

    question_id: str
    is_valid: bool
    flags: Tuple[QuestionValidationFlag, ...] = (QuestionValidationFlag.VALID,)
    diagnostic_message: str = "Question is grounded, neutral, and atomic."

    @property
    def has_presupposition(self) -> bool:
        return QuestionValidationFlag.PRESUPPOSES_ANSWER in self.flags

    @property
    def is_ungrounded(self) -> bool:
        return QuestionValidationFlag.UNGROUNDED_REFERENT in self.flags


@dataclass(frozen=True)
class HarnessAmplificationProvenance:
    """Telemetry capturing execution and feed characteristics for future optimization.

    Preserves empirical data for the future Harness Amplification requirement
    without implementing autonomous learning today.
    """

    turn_id: str
    framing_method: QuestionFramingMethod
    discovered_uncertainties_count: int
    critical_uncertainties_count: int
    omitted_critical_uncertainties_count: int
    framed_questions_count: int
    validated_questions_count: int
    rejected_questions_count: int
    framing_latency_ms: float = 0.0
    validation_latency_ms: float = 0.0
    tokens_consumed: int = 0
